import { mkdir, writeFile } from "node:fs/promises";
import * as icons from "simple-icons";

// Only these paths are shipped to the browser. Keep each upstream source URL.
const selected = {
  react: "siReact", nextjs: "siNextdotjs", typescript: "siTypescript",
  tailwindcss: "siTailwindcss", go: "siGo", postgresql: "siPostgresql",
  supabase: "siSupabase", gsap: "siGsap", solidity: "siSolidity",
  vitest: "siVitest", radixui: "siRadixui", html: "siHtml5",
  css: "siCss", javascript: "siJavascript", github: "siGithub", instagram: "siInstagram",
};
const data = {};
for (const [key, exportName] of Object.entries(selected)) {
  const icon = icons[exportName];
  if (!icon?.path || !icon.source) throw new Error(`Missing upstream brand: ${exportName}`);
  data[key] = { title: icon.title, slug: icon.slug, hex: icon.hex, path: icon.path, source: icon.source };
}
const root = new URL("../", import.meta.url);
await mkdir(new URL("src/lib/", root), { recursive: true });
await writeFile(new URL("src/lib/brand-icons.ts", root), `// Generated by npm run icons:sync from Simple Icons 16.35.0 (CC0-1.0).\n// Do not redraw these logos; update the pinned source package instead.\nexport const brandIcons = ${JSON.stringify(data, null, 2)} as const;\n`);
console.log(`Synced ${Object.keys(data).length} brand SVGs.`);
